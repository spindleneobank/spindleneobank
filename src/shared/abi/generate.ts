/**
 * Regenerates SpindleRegistry/SpindleStaking/SpindleClaims/BuyerVault ABI files from the compiled contracts.
 * Run: `cd app/contracts && forge build && cd .. && bun run src/shared/abi/generate.ts`
 * Dev-only script (uses Bun); not exported from the shared index.
 */
import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const names = ['SpindleRegistry', 'SpindleStaking', 'SpindleClaims', 'BuyerVault'] as const;
const cwd = new URL('../../../contracts', import.meta.url).pathname;
for (const name of names) {
  const r = spawnSync('forge', ['inspect', name, 'abi', '--json'], { cwd, encoding: 'utf8' });
  if (r.status !== 0) throw new Error(`forge inspect ${name} failed: ${r.stderr}`);
  const abi = JSON.stringify(JSON.parse(r.stdout), null, 2);
  const exportName = `${name[0]?.toLowerCase()}${name.slice(1)}Abi`;
  writeFileSync(
    new URL(`./${name}.ts`, import.meta.url),
    `// GENERATED by src/shared/abi/generate.ts from \`forge inspect ${name} abi --json\`. Do not edit.\nexport const ${exportName} = ${abi} as const;\n`,
  );
}
