/**
 * Canonical ABI generator: reads `contracts/out/<Name>.sol/<Name>.json` (forge build) and writes
 * `src/shared/abi/<Name>.ts` as `export const <name>Abi = [...] as const`.
 * Run: `bun run abi:export` (builds the contracts first).
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

export const ABI_CONTRACTS = [
  'SpindleRegistry',
  'SpindleStaking',
  'SpindleClaims',
  'BuyerVault',
  'RelayStubDepository',
] as const;

const contractsDir = new URL('..', import.meta.url).pathname;
const abiDir = new URL('../../src/shared/abi/', import.meta.url);

export function exportAbis(build = true): void {
  if (build) {
    const r = spawnSync('forge', ['build'], { cwd: contractsDir, stdio: 'inherit' });
    if (r.status !== 0) throw new Error('forge build failed');
  }
  for (const name of ABI_CONTRACTS) {
    const artifact = JSON.parse(readFileSync(`${contractsDir}out/${name}.sol/${name}.json`, 'utf8')) as {
      abi: unknown;
    };
    const exportName = `${name[0]?.toLowerCase()}${name.slice(1)}Abi`;
    writeFileSync(
      new URL(`${name}.ts`, abiDir),
      `// GENERATED by contracts/script/export-abis.ts from contracts/out/${name}.sol/${name}.json. Do not edit.\nexport const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
    );
  }
  // Keep `biome check` green on the generated files.
  const files = ABI_CONTRACTS.map((n) => `src/shared/abi/${n}.ts`);
  spawnSync('bunx', ['biome', 'check', '--write', ...files], {
    cwd: new URL('../..', import.meta.url).pathname,
  });
}

if (import.meta.main) exportAbis(process.env.SKIP_FORGE_BUILD !== '1');
